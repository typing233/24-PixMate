"""Sprite data structures and built-in pixel art definitions."""

from dataclasses import dataclass


@dataclass
class Sprite:
    name: str
    width: int
    height: int
    palette: list[tuple[int, int, int] | None]
    frames: list[list[list[int]]]

    @property
    def frame_count(self) -> int:
        return len(self.frames)


